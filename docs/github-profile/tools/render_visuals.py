PROMPTS = {
    name: ("GitHub Profile hero banner: " if name == "hero" else
           "GitHub Profile research card: ") + prompt
    for name, prompt in PROMPTS.items()
}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fetch(name, image=None):
    """Archive backend-generated bytes; reruns never replace existing artwork."""
    output = ASSETS / ("hero-source.jpg" if name == "hero" else f"{name}.jpg")
    if output.exists() and digest(output) not in {
            PENDING_THUMBNAIL_SHA, PENDING_SOURCE_SHA}:
        raise ValueError(f"Existing artwork retained: {output}")
    url = ENDPOINT + "?" + urlencode({
        "prompt": PROMPTS[name], "image_size": "landscape_16_9",
    })
    if image:
        payload = Path(image).read_bytes()
    else:
        with urlopen(url, timeout=180) as response:
            content_type = response.headers.get("Content-Type", "")
            payload = response.read()
        if not content_type.startswith("image/"):
            raise ValueError(f"Expected image response, received {content_type}")
    with Image.open(BytesIO(payload)) as generated:
        original_size = list(generated.size)
        picture = ImageOps.exif_transpose(generated).convert("RGB")
        probe = BytesIO()
        ImageOps.fit(picture, (768, 432), Image.Resampling.LANCZOS).save(
            probe, format="JPEG", quality=90, optimize=True)
        if hashlib.sha256(probe.getvalue()).hexdigest() == PENDING_THUMBNAIL_SHA:
            raise RuntimeError(
                f"Image service is still generating {name}; do not publish the pending image.")
        if name != "hero":
            picture = ImageOps.fit(picture, (768, 432), Image.Resampling.LANCZOS)
        picture.save(output, quality=90, optimize=True)
    provenance = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "source_url": url,
        "generation_method": ("GenerateImage backend text-to-image API" if image else
                              "Direct text_to_image URL"),
        "prompt": PROMPTS[name],
        "image_size": "landscape_16_9",
        "original_dimensions": original_size,
        "saved_dimensions": list(picture.size),
        "file": output.name,
        "sha256": digest(output),
        "purpose": "Decorative research artwork; not experimental evidence or a product screenshot.",
    }
    (ASSETS / f"{name}.provenance.json").write_text(
        json.dumps(provenance, ensure_ascii=False, indent=2) + "\n")
    if name == "hero":
        render_header()
    return provenance


def font(size, bold=False, mono=False):
    candidates = (
        ["/System/Library/Fonts/Menlo.ttc",
         "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"] if mono else
        ["/System/Library/Fonts/Supplemental/Arial Bold.ttf",
         "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"] if bold else
        ["/System/Library/Fonts/Supplemental/Arial.ttf",
         "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"]
    )
    for candidate in candidates:
        if Path(candidate).is_file():
            return ImageFont.truetype(candidate, size)
    raise ValueError("Install Arial or DejaVu fonts before rendering the header")


def render_header():
    """Adapt ryme.md's MIT Sleek Hero: name fitting, underline and corner marks.

    Original: Ryan Polasky, aede040201f5ed5168eb74c5e1fe319895b724ed.
    See ../LICENSE-ryme.md. Static raster composition adds generated artwork,
    uses left alignment and retains a readable text block on small displays.
    """
    width, height = 1280, 460
    artwork = Image.open(ASSETS / "hero-source.jpg").convert("RGB")
    canvas = ImageOps.fit(artwork, (width, height), Image.Resampling.LANCZOS,
                          centering=(0.65, 0.5)).convert("RGBA")
    # Fade the picture under the left-aligned name, keeping its right side visible.
    shade = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    shade_draw = ImageDraw.Draw(shade)
    for x in range(width):
        alpha = round(240 * max(0, 1 - x / 1050))
        shade_draw.line([(x, 0), (x, height)], fill=(9, 20, 32, alpha))
    canvas = Image.alpha_composite(canvas, shade)
    draw = ImageDraw.Draw(canvas)
    accent, foreground, muted = "#5cdbc5", "#f4f7f9", "#b9c9d5"
    pad = 60
    # Static counterpart of the template's two top corner decorations.
    for x, direction in [(pad, 1), (width - pad, -1)]:
        draw.line([(x, 44), (x + direction * 24, 44)], fill=accent, width=2)
        draw.line([(x, 44), (x, 68)], fill=accent, width=2)
    draw.text((pad, 89), "STEIN / RESEARCH & NOTES", font=font(19, mono=True),
              fill=accent)
    name = "Yuxiang Wang"
    for size in [76, 68, 60, 52]:
        name_font = font(size, bold=True)
        if draw.textlength(name, font=name_font) <= 640:
            break
    draw.text((pad - 3, 142), name, font=name_font, fill=foreground)
    underline_width = min(640, round(draw.textlength(name, font=name_font)))
    draw.line([(pad, 244), (pad + underline_width, 244)], fill=accent, width=3)
    draw.text((pad, 275), "Agentic RL · Scientific task synthesis",
              font=font(24), fill=foreground)
    draw.text((pad, 319), "GUI agents · Diffusion language models",
              font=font(23), fill=muted)
    canvas.convert("RGB").save(ASSETS / "hero.jpg", quality=93, optimize=True)


def manifest():
    records = []
    for name in PROMPTS:
        provenance = json.loads((ASSETS / f"{name}.provenance.json").read_text())
        output = ASSETS / ("hero.jpg" if name == "hero" else f"{name}.jpg")
        with Image.open(output) as picture:
            dimensions = list(picture.size)
        records.append({
            "file": output.name, "width": dimensions[0], "height": dimensions[1],
            "bytes": output.stat().st_size, "sha256": digest(output),
            "provenance": f"{name}.provenance.json",
            "source_url": provenance["source_url"],
        })
    result = {
        "version": 1,
        "template": {
            "repository": "https://github.com/ryanpolasky/ryme.md",
            "commit": "aede040201f5ed5168eb74c5e1fe319895b724ed",
            "source": "src/lib/templates/sleek-header.ts",
            "license": "MIT",
            "adaptation": "Static image header with generated artwork and left-aligned text.",
        },
        "assets": records,
    }
    (ASSETS / "manifest.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--fetch", choices=PROMPTS)
    action.add_argument("--adopt", choices=PROMPTS)
    action.add_argument("--header", action="store_true")
    action.add_argument("--manifest", action="store_true")
    parser.add_argument("--image", type=Path,
                        help="Original output from GenerateImage; required with --adopt")
    args = parser.parse_args()
    if bool(args.adopt) != bool(args.image):
        parser.error("--adopt and --image must be supplied together")
    if not ASSETS.is_dir():
        raise SystemExit(f"Create the assets directory first: {ASSETS}")
    result = (fetch(args.fetch) if args.fetch else
              fetch(args.adopt, args.image) if args.adopt else
              render_header() if args.header else manifest())
    print(json.dumps(result, ensure_ascii=False, indent=2))
